CREATE TABLE public.profile_community_posts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  texto text NOT NULL DEFAULT '',
  attachment_type text CHECK (attachment_type IN ('reel', 'evento')),
  reel_id bigint REFERENCES public.reels(id) ON DELETE CASCADE,
  event_id bigint REFERENCES public.eventos(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  CONSTRAINT profile_community_posts_attachment CHECK (
    (attachment_type IS NULL AND reel_id IS NULL AND event_id IS NULL) OR
    (attachment_type = 'reel' AND reel_id IS NOT NULL AND event_id IS NULL) OR
    (attachment_type = 'evento' AND event_id IS NOT NULL AND reel_id IS NULL)
  )
);
