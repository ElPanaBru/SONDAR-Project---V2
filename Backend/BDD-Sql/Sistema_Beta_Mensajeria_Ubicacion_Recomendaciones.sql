BEGIN;

SELECT pg_advisory_xact_lock(hashtext('sondar:sistemas-beta:v1'));

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_extension e
    JOIN pg_namespace n ON n.oid = e.extnamespace
    WHERE e.extname = 'postgis' AND n.nspname = 'gis'
  ) THEN
    RAISE EXCEPTION 'PostGIS debe estar instalado en el esquema gis antes de ejecutar esta migracion';
  END IF;
END
$$;

-- ---------------------------------------------------------------------------
-- 1. Ubicacion de eventos indexada espacialmente
-- ---------------------------------------------------------------------------

ALTER TABLE public.eventos
  ADD COLUMN IF NOT EXISTS ubicacion_geog gis.geography(Point, 4326);

CREATE OR REPLACE FUNCTION public.sincronizar_ubicacion_evento()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  IF NEW.latitud IS NULL OR NEW.longitud IS NULL THEN
    NEW.ubicacion_geog := NULL;
  ELSE
    NEW.ubicacion_geog := gis.ST_SetSRID(
      gis.ST_MakePoint(NEW.longitud, NEW.latitud),
      4326
    )::gis.geography;
  END IF;
  RETURN NEW;
END;
$$;

UPDATE public.eventos
SET ubicacion_geog = gis.ST_SetSRID(
  gis.ST_MakePoint(longitud, latitud),
  4326
)::gis.geography
WHERE latitud IS NOT NULL
  AND longitud IS NOT NULL
  AND ubicacion_geog IS NULL;

DROP TRIGGER IF EXISTS eventos_sincronizar_ubicacion ON public.eventos;
CREATE TRIGGER eventos_sincronizar_ubicacion
BEFORE INSERT OR UPDATE OF latitud, longitud
ON public.eventos
FOR EACH ROW
EXECUTE FUNCTION public.sincronizar_ubicacion_evento();

CREATE INDEX IF NOT EXISTS eventos_ubicacion_geog_gist_idx
  ON public.eventos USING gist (ubicacion_geog);

