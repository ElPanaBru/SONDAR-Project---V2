-- 2. Mensajeria directa
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.conversations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  kind text NOT NULL DEFAULT 'direct' CHECK (kind IN ('direct')),
  direct_key text NOT NULL UNIQUE,
  created_by uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at timestamptz NOT NULL DEFAULT timezone('utc'::text, now()),
  last_message_at timestamptz NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE INDEX IF NOT EXISTS conversations_last_message_idx
  ON public.conversations (last_message_at DESC, id);

CREATE TABLE IF NOT EXISTS public.conversation_members (
  conversation_id uuid NOT NULL REFERENCES public.conversations(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  joined_at timestamptz NOT NULL DEFAULT timezone('utc'::text, now()),
  last_read_at timestamptz NOT NULL DEFAULT timezone('utc'::text, now()),
  muted boolean NOT NULL DEFAULT false,
  archived_at timestamptz,
  PRIMARY KEY (conversation_id, user_id)
);

CREATE INDEX IF NOT EXISTS conversation_members_user_idx
  ON public.conversation_members (user_id, conversation_id);

CREATE TABLE IF NOT EXISTS public.messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id uuid NOT NULL REFERENCES public.conversations(id) ON DELETE CASCADE,
  sender_id uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  body text NOT NULL,
  reply_to_id bigint REFERENCES public.messages(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT timezone('utc'::text, now()),
  edited_at timestamptz,
  deleted_at timestamptz,
  CONSTRAINT messages_body_length_check CHECK (
    deleted_at IS NOT NULL OR length(trim(body)) BETWEEN 1 AND 2000
  )
);

CREATE INDEX IF NOT EXISTS messages_conversation_cursor_idx
  ON public.messages (conversation_id, id DESC);
CREATE INDEX IF NOT EXISTS messages_sender_rate_idx
  ON public.messages (sender_id, created_at DESC);

CREATE OR REPLACE FUNCTION public.is_conversation_member(
  conversation_uuid uuid,
  member_uuid uuid DEFAULT auth.uid()
)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.conversation_members cm
    WHERE cm.conversation_id = conversation_uuid
      AND cm.user_id = member_uuid
  );
$$;

REVOKE ALL ON FUNCTION public.is_conversation_member(uuid, uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.is_conversation_member(uuid, uuid) TO authenticated;

CREATE OR REPLACE FUNCTION public.actualizar_conversacion_por_mensaje()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  UPDATE public.conversations
  SET last_message_at = NEW.created_at,
      updated_at = timezone('utc'::text, now())
  WHERE id = NEW.conversation_id;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS messages_actualizar_conversacion ON public.messages;
CREATE TRIGGER messages_actualizar_conversacion
AFTER INSERT ON public.messages
FOR EACH ROW
EXECUTE FUNCTION public.actualizar_conversacion_por_mensaje();

-- Broadcast desde la base: los clientes no dependen de escuchar toda la tabla.
CREATE OR REPLACE FUNCTION public.broadcast_message_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  conversation_uuid uuid;
BEGIN
  conversation_uuid := COALESCE(NEW.conversation_id, OLD.conversation_id);
  PERFORM realtime.broadcast_changes(
    'conversation:' || conversation_uuid::text,
    TG_OP,
    TG_OP,
    TG_TABLE_NAME,
    TG_TABLE_SCHEMA,
    NEW,
    OLD
  );
  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS messages_broadcast_change ON public.messages;
CREATE TRIGGER messages_broadcast_change
AFTER INSERT OR UPDATE OR DELETE ON public.messages
FOR EACH ROW
EXECUTE FUNCTION public.broadcast_message_change();

CREATE OR REPLACE FUNCTION public.broadcast_conversation_read_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF OLD.last_read_at IS DISTINCT FROM NEW.last_read_at THEN
    PERFORM realtime.send(
      jsonb_build_object(
        'user_id', NEW.user_id,
        'last_read_at', NEW.last_read_at
      ),
      'read',
      'conversation:' || NEW.conversation_id::text,
      true
    );
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS conversation_members_broadcast_read ON public.conversation_members;
CREATE TRIGGER conversation_members_broadcast_read
AFTER UPDATE OF last_read_at ON public.conversation_members
FOR EACH ROW
EXECUTE FUNCTION public.broadcast_conversation_read_change();

