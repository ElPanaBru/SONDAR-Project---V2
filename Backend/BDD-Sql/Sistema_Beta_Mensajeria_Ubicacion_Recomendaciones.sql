CREATE TABLE IF NOT EXISTS public.reel_playback_sessions (
  id uuid PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  reel_id bigint NOT NULL REFERENCES public.reels(id) ON DELETE CASCADE,
  listened_ms integer NOT NULL DEFAULT 0 CHECK (listened_ms BETWEEN 0 AND 3600000),
  duration_ms integer CHECK (duration_ms IS NULL OR duration_ms BETWEEN 1 AND 3600000),
  completion_ratio numeric(5, 4) NOT NULL DEFAULT 0
    CHECK (completion_ratio BETWEEN 0 AND 1),
  completed boolean NOT NULL DEFAULT false,
  skipped boolean NOT NULL DEFAULT false,
  replay_count smallint NOT NULL DEFAULT 0 CHECK (replay_count BETWEEN 0 AND 100),
  started_at timestamptz NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at timestamptz NOT NULL DEFAULT timezone('utc'::text, now()),
  UNIQUE (id, user_id)
);

CREATE INDEX IF NOT EXISTS reel_playback_user_recent_idx
  ON public.reel_playback_sessions (user_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS reel_playback_reel_idx
  ON public.reel_playback_sessions (reel_id, updated_at DESC);

CREATE TABLE IF NOT EXISTS public.user_genre_affinity (
  user_id uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  genre text NOT NULL,
  behavioral_score numeric(10, 3) NOT NULL DEFAULT 0,
  listening_sessions integer NOT NULL DEFAULT 0,
  last_interaction_at timestamptz NOT NULL DEFAULT timezone('utc'::text, now()),
  PRIMARY KEY (user_id, genre)
);

CREATE INDEX IF NOT EXISTS user_genre_affinity_score_idx
  ON public.user_genre_affinity (user_id, behavioral_score DESC);

CREATE OR REPLACE FUNCTION public.playback_signal_score(
  listened integer,
  ratio numeric,
  was_completed boolean,
  was_skipped boolean,
  replays smallint
)
RETURNS numeric
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
SET search_path = ''
AS $$
  SELECT LEAST(16::numeric, GREATEST(0, COALESCE(listened, 0))::numeric / 3000)
       + LEAST(14::numeric, GREATEST(0, COALESCE(ratio, 0)) * 14)
       + CASE WHEN COALESCE(was_completed, false) THEN 5 ELSE 0 END
       + LEAST(8::numeric, GREATEST(0, COALESCE(replays, 0))::numeric * 4)
       - CASE
           WHEN COALESCE(was_skipped, false) AND COALESCE(listened, 0) < 5000 THEN 9
           WHEN COALESCE(was_skipped, false) THEN 3
           ELSE 0
         END;
$$;

CREATE OR REPLACE FUNCTION public.actualizar_afinidad_desde_escucha()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  genre_value text;
  delta numeric := 0;
  session_delta integer := 0;
BEGIN
  SELECT lower(r.genero) INTO genre_value
  FROM public.reels r
  WHERE r.id = COALESCE(NEW.reel_id, OLD.reel_id);

  IF genre_value IS NULL OR genre_value = '' THEN
    IF TG_OP = 'DELETE' THEN
      RETURN OLD;
    END IF;
    RETURN NEW;
  END IF;

  IF TG_OP = 'INSERT' THEN
    delta := public.playback_signal_score(
      NEW.listened_ms, NEW.completion_ratio, NEW.completed, NEW.skipped, NEW.replay_count
    );
    session_delta := 1;
  ELSIF TG_OP = 'UPDATE' THEN
    delta := public.playback_signal_score(
      NEW.listened_ms, NEW.completion_ratio, NEW.completed, NEW.skipped, NEW.replay_count
    ) - public.playback_signal_score(
      OLD.listened_ms, OLD.completion_ratio, OLD.completed, OLD.skipped, OLD.replay_count
    );
  ELSE
    delta := -public.playback_signal_score(
      OLD.listened_ms, OLD.completion_ratio, OLD.completed, OLD.skipped, OLD.replay_count
    );
    session_delta := -1;
  END IF;

  INSERT INTO public.user_genre_affinity (
    user_id, genre, behavioral_score, listening_sessions, last_interaction_at
  ) VALUES (
    COALESCE(NEW.user_id, OLD.user_id),
    genre_value,
    GREATEST(-50::numeric, LEAST(250::numeric, delta)),
    GREATEST(0, session_delta),
    timezone('utc'::text, now())
  )
  ON CONFLICT (user_id, genre) DO UPDATE
  SET behavioral_score = GREATEST(
        -50::numeric,
        LEAST(250::numeric, public.user_genre_affinity.behavioral_score + delta)
      ),
      listening_sessions = GREATEST(
        0,
        public.user_genre_affinity.listening_sessions + session_delta
      ),
      last_interaction_at = timezone('utc'::text, now());

  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS reel_playback_actualizar_afinidad ON public.reel_playback_sessions;
CREATE TRIGGER reel_playback_actualizar_afinidad
AFTER INSERT OR UPDATE OR DELETE ON public.reel_playback_sessions
FOR EACH ROW
EXECUTE FUNCTION public.actualizar_afinidad_desde_escucha();

