ALTER TABLE public.conversations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.conversation_members ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reel_playback_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_genre_affinity ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS conversations_member_read ON public.conversations;
CREATE POLICY conversations_member_read ON public.conversations
FOR SELECT TO authenticated
USING (EXISTS (
  SELECT 1
  WHERE public.is_conversation_member(conversations.id, (SELECT auth.uid()))
));

DROP POLICY IF EXISTS conversation_members_member_read ON public.conversation_members;
CREATE POLICY conversation_members_member_read ON public.conversation_members
FOR SELECT TO authenticated
USING (public.is_conversation_member(
  conversation_members.conversation_id,
  (SELECT auth.uid())
));

DROP POLICY IF EXISTS messages_member_read ON public.messages;
CREATE POLICY messages_member_read ON public.messages
FOR SELECT TO authenticated
USING (public.is_conversation_member(messages.conversation_id, (SELECT auth.uid())));

DROP POLICY IF EXISTS messages_member_insert ON public.messages;
CREATE POLICY messages_member_insert ON public.messages
FOR INSERT TO authenticated
WITH CHECK (
  sender_id = (SELECT auth.uid())
  AND public.is_conversation_member(messages.conversation_id, (SELECT auth.uid()))
);

DROP POLICY IF EXISTS messages_sender_change ON public.messages;
CREATE POLICY messages_sender_change ON public.messages
FOR UPDATE TO authenticated
USING (sender_id = (SELECT auth.uid()))
WITH CHECK (
  sender_id = (SELECT auth.uid())
  AND public.is_conversation_member(messages.conversation_id, (SELECT auth.uid()))
);

DROP POLICY IF EXISTS reel_playback_own ON public.reel_playback_sessions;
CREATE POLICY reel_playback_own ON public.reel_playback_sessions
FOR ALL TO authenticated
USING (user_id = (SELECT auth.uid()))
WITH CHECK (user_id = (SELECT auth.uid()));

DROP POLICY IF EXISTS user_genre_affinity_own_read ON public.user_genre_affinity;
CREATE POLICY user_genre_affinity_own_read ON public.user_genre_affinity
FOR SELECT TO authenticated
USING (user_id = (SELECT auth.uid()));

GRANT SELECT ON public.conversations, public.conversation_members, public.messages,
  public.reel_playback_sessions, public.user_genre_affinity TO authenticated;
REVOKE INSERT, UPDATE, DELETE ON public.conversations, public.conversation_members,
  public.messages, public.reel_playback_sessions, public.user_genre_affinity FROM authenticated;

DROP POLICY IF EXISTS sondar_conversation_realtime_read ON realtime.messages;
CREATE POLICY sondar_conversation_realtime_read ON realtime.messages
FOR SELECT TO authenticated
USING (
  extension IN ('broadcast', 'presence')
  AND EXISTS (
    SELECT 1
    FROM public.conversation_members cm
    WHERE cm.user_id = (SELECT auth.uid())
      AND 'conversation:' || cm.conversation_id::text = realtime.topic()
  )
);

DROP POLICY IF EXISTS sondar_conversation_realtime_send ON realtime.messages;
CREATE POLICY sondar_conversation_realtime_send ON realtime.messages
FOR INSERT TO authenticated
WITH CHECK (
  extension IN ('broadcast', 'presence')
  AND EXISTS (
    SELECT 1
    FROM public.conversation_members cm
    WHERE cm.user_id = (SELECT auth.uid())
      AND 'conversation:' || cm.conversation_id::text = realtime.topic()
  )
);

COMMIT;
